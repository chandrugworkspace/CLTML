def format_latex_bib():
    lines = ["\\begin{thebibliography}{00}"]
    for r in AUTHENTIC_REFS:
        authors = r["authors_tex"]
        title = r["title"]
        venue = r["venue_tex"]
        year = r["year"]
        pages = r["pages"]
        doi_str = f", doi: {r['doi']}" if r.get("doi") else ""
        if r.get("is_book"):
            lines.append(f"\\bibitem{{{r['key']}}} {authors}, \\textit{{{title}}}, {venue}, {year}{doi_str}.")
        else:
            if pages:
                lines.append(f"\\bibitem{{{r['key']}}} {authors}, ``{title},'' in \\textit{{{venue}}}, {year}, {pages}{doi_str}.")
            else:
                lines.append(f"\\bibitem{{{r['key']}}} {authors}, ``{title},'' \\textit{{{venue}}}, {year}{doi_str}.")
    lines.append("\\end{thebibliography}")
    return "\n".join(lines)

