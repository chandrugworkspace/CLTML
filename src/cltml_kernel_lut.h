/* Genuinely branchless 3-bit quantization (8 bins, 7 thresholds: zero data-dependent loads) */
static inline __attribute__((always_inline)) uint32_t cltml_quantize_3bit_kernel(
    int32_t val, const int32_t t[7]
) {
    return (uint32_t)(val > t[0]) + (uint32_t)(val > t[1]) +
           (uint32_t)(val > t[2]) + (uint32_t)(val > t[3]) +
           (uint32_t)(val > t[4]) + (uint32_t)(val > t[5]) +
           (uint32_t)(val > t[6]);
}

/* Genuinely branchless 4-bit quantization (16 bins, 15 thresholds: zero data-dependent loads) */
static inline __attribute__((always_inline)) uint32_t cltml_quantize_4bit_kernel(
    int32_t val, const int32_t t[15]
) {
    return (uint32_t)(val > t[0])  + (uint32_t)(val > t[1])  +
           (uint32_t)(val > t[2])  + (uint32_t)(val > t[3])  +
           (uint32_t)(val > t[4])  + (uint32_t)(val > t[5])  +
           (uint32_t)(val > t[6])  + (uint32_t)(val > t[7])  +
           (uint32_t)(val > t[8])  + (uint32_t)(val > t[9])  +
           (uint32_t)(val > t[10]) + (uint32_t)(val > t[11]) +
           (uint32_t)(val > t[12]) + (uint32_t)(val > t[13]) +
           (uint32_t)(val > t[14]);
}

/* Defensive input validation and saturation clamping */
static inline __attribute__((always_inline)) int32_t cltml_clamp_feature(
    int32_t val, int32_t min_v, int32_t max_v
) {
    if (val < min_v) return min_v;
    if (val > max_v) return max_v;
    return val;
}

