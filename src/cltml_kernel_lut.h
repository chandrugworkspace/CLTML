/*
 * Design A Kernel Selector: 4 Features x 3 Bits = 12-Bit Index (4,096 B LUT)
 * Fast path: ~10-14 ns; strictly integer; static fallback if disabled/invalid.
 */
static inline __attribute__((always_inline)) uint8_t cltml_kernel_select_4x3(
    const int32_t features_fp[CLTML_NUM_FEATURES],
    int enabled
) {
    uint32_t b0, b1, b2, b3, idx_12bit;

    /* Fallback immediately if administratively disabled */
    if (!enabled || !features_fp) {
        return CLTML_POLICY_FALLBACK;
    }

    /* Defensive clamping to valid fixed-point domain (0..10,000 for percentages / rates) */
    int32_t f_numa = cltml_clamp_feature(features_fp[CLTML_KERNEL_4X3_FEAT_IDX[0]], 0, 10000);
    int32_t f_qdep = cltml_clamp_feature(features_fp[CLTML_KERNEL_4X3_FEAT_IDX[1]], 0, 12800);
    int32_t f_cas  = cltml_clamp_feature(features_fp[CLTML_KERNEL_4X3_FEAT_IDX[2]], 0, 10000);
    int32_t f_llc  = cltml_clamp_feature(features_fp[CLTML_KERNEL_4X3_FEAT_IDX[3]], 0, 10000);

    b0 = cltml_quantize_3bit_kernel(f_numa, CLTML_KERNEL_4X3_THRESH_FP[0]);
    b1 = cltml_quantize_3bit_kernel(f_qdep, CLTML_KERNEL_4X3_THRESH_FP[1]);
    b2 = cltml_quantize_3bit_kernel(f_cas,  CLTML_KERNEL_4X3_THRESH_FP[2]);
    b3 = cltml_quantize_3bit_kernel(f_llc,  CLTML_KERNEL_4X3_THRESH_FP[3]);

    idx_12bit = (b0 << 9) | (b1 << 6) | (b2 << 3) | b3;

    /* Mask strictly with 0x0FFF to guarantee safe in-bounds read in .rodata */
    return cltml_kernel_lut_4x3[idx_12bit & 0x0FFFu];
}

/*
 * Pre-Binned Register Fast Path for Design A: (b0, b1, b2, b3) each 0..7 (3 bits)
 * Hot path: Only shifts, ORs, and 1 byte memory read (~2-4 ns).
 */
static inline __attribute__((always_inline)) uint8_t cltml_kernel_select_direct_4x3(
    uint32_t b0, uint32_t b1, uint32_t b2, uint32_t b3,
    int enabled
) {
    if (!enabled) {
        return CLTML_POLICY_FALLBACK;
    }
    uint32_t idx_12bit = ((b0 & 0x7u) << 9) | ((b1 & 0x7u) << 6) | ((b2 & 0x7u) << 3) | (b3 & 0x7u);
    return cltml_kernel_lut_4x3[idx_12bit & 0x0FFFu];
}

/*
 * Pre-Binned Register Fast Path for Design B: (b0, b1, b2) each 0..15 (4 bits)
 * Hot path: Only 2 shifts, 2 ORs, and 1 byte memory read (~2-4 ns).
 */
static inline __attribute__((always_inline)) uint8_t cltml_kernel_select_direct(
    uint32_t b0, uint32_t b1, uint32_t b2,
    int enabled
) {
    if (!enabled) {
        return CLTML_POLICY_FALLBACK;
    }
    uint32_t idx_12bit = ((b0 & 0xFu) << 8) | ((b1 & 0xFu) << 4) | (b2 & 0xFu);
    return cltml_kernel_lut_4x3[idx_12bit & 0x0FFFu];
}

/*
 * Map CLTML policy code (0..3) to Tier 1 Adaptive Mutex spin ceiling
 */
static inline __attribute__((always_inline)) uint32_t cltml_policy_to_spin_budget(uint8_t policy) {
    switch (policy) {
        case LOCK_PRIM_QSPINLOCK:       return CLTML_SPIN_BUDGET_HIGH;   /* Spin actively: low contention (1024) */
        case LOCK_PRIM_COHORT_LOCK:     return CLTML_SPIN_BUDGET_COHORT; /* NUMA batch boundary (64)             */
        case LOCK_PRIM_MUTEX_LOW_SPIN:  return CLTML_SPIN_BUDGET_LOW;    /* Sleep early: high queue depth (32)   */
        case LOCK_PRIM_MUTEX_HIGH_SPIN: return CLTML_SPIN_BUDGET_MED;    /* Moderate contention spin (256)       */
        default:                        return CLTML_SPIN_BUDGET_MED;
    }
}

